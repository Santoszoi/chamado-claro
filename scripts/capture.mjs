import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
await mkdir('media', { recursive: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1, recordVideo: { dir: 'test-results/video', size: { width: 1440, height: 1100 } } });
const page = await context.newPage();
await page.goto('http://127.0.0.1:4173');
await page.getByRole('heading', { name: 'Como podemos ajudar?' }).waitFor();
await page.screenshot({ path: 'media/01-formulario.png', fullPage: true });
await page.waitForTimeout(2200);
// A real browser recording with deliberate pauses for viewers, not performance measurements.
await page.getByLabel('Nome', { exact: true }).fill('Alex Silva');
await page.getByRole('button', { name: 'Simular abertura' }).click();
await page.screenshot({ path: 'media/02-erros.png', fullPage: true });
await page.waitForTimeout(3000);
await page.getByRole('link', { name: /^E-mail: Informe/ }).click();
await page.keyboard.type('alex@example.com', { delay: 70 });
await page.keyboard.press('Tab');
await page.keyboard.type('Nao consigo acessar o painel', { delay: 60 });
await page.keyboard.press('Tab'); await page.keyboard.press('ArrowDown');
await page.keyboard.press('Tab'); await page.keyboard.press('Tab');
await page.keyboard.type('Ao entrar com a conta ficticia, o painel informa acesso negado. Esperava visualizar meus chamados.', { delay: 38 });
await page.waitForTimeout(1800);
await page.keyboard.press('Tab'); await page.keyboard.press('Enter');
await page.getByRole('heading', { name: 'Seu relato está organizado.' }).waitFor();
await page.screenshot({ path: 'media/03-confirmacao.png', fullPage: true });
await page.waitForTimeout(4000);
const video = page.video();
await context.close();
await video.saveAs('media/chamado-claro.webm');
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
await mobile.goto('http://127.0.0.1:4173');
await mobile.getByRole('heading', { name: 'Como podemos ajudar?' }).waitFor();
await mobile.screenshot({ path: 'media/04-mobile.png', fullPage: true });
await browser.close();
console.log('Saved four real screenshots and browser recording.');
